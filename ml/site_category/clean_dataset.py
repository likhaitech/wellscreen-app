"""
Cleans the raw UT1 Blacklists category files in raw/ into a single labeled
dataset (domain,category) usable for WellScreen's proposed harmful-site
category detection (manuscript Table 6: "harmful website/category attempt").

Source: UT1 Blacklists (Universite Toulouse Capitole), maintained by
Fabrice Prigent - http://dsi.ut-capitole.fr/blacklists/index_en.php
Mirror used: https://github.com/olbat/ut1-blacklists (synced daily from the
UT1 site, CC BY-SA 4.0 licensed).

This is REAL, third-party-collected data - domain names that have been
manually reviewed and categorized by the UT1 project over many years for
use in real school/university web filters. It is not synthetic and not
generated by this project.

Categories included, and why:
  - gambling: casino/betting sites (Table 6's closest match for "harmful
    website/category attempt" in a general sense)
  - drugs (UT1 folder name: "drogue"): drug-related sites
  - dangerous_material: sites describing how to make weapons/explosives;
    UT1's own file also includes some pro-eating-disorder domains, which
    are self-harm-adjacent even though UT1 has no dedicated self-harm
    category (see README.md for the honest gap here)

Deliberately NOT included: UT1's "adult" category (4.6 million domains -
not practical to vet, store, or ship as a mobile asset for a school
project, and not needed to demonstrate the cleaning methodology, which is
the point of this exercise). A production version of this feature would
add it the same way, from the same source.

Run: python3 clean_dataset.py
Writes: output/cleaned_site_categories.csv, output/cleaning_report.txt
"""

import csv
import ipaddress
import re
from collections import defaultdict
from pathlib import Path

RAW_DIR = Path(__file__).parent / "raw"
OUTPUT_DIR = Path(__file__).parent / "output"

SOURCES = {
    "gambling": RAW_DIR / "gambling_domains.txt",
    "drugs": RAW_DIR / "drugs_domains.txt",
    "dangerous_material": RAW_DIR / "dangerous_material_domains.txt",
}

# A deliberately simple, permissive FQDN check: labels separated by dots,
# each label alphanumeric/hyphen, 2+ char TLD. This is a data-QUALITY
# filter (reject obvious garbage), not a strict RFC 1035 validator.
DOMAIN_RE = re.compile(
    r"^(?!-)[a-z0-9-]{1,63}(?<!-)(\.(?!-)[a-z0-9-]{1,63}(?<!-))*\.[a-z]{2,}$"
)


def is_ip_address(token):
    try:
        ipaddress.ip_address(token)
        return True
    except ValueError:
        return False


def clean_category(name, path, report):
    raw_lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    report["raw_line_count"][name] = len(raw_lines)

    blank_or_comment = 0
    ip_entries = []
    malformed = []
    seen_in_category = set()
    duplicates_in_category = 0
    cleaned = []

    for raw_line in raw_lines:
        token = raw_line.strip().lower()

        if not token or token.startswith("#") or token.startswith("//"):
            blank_or_comment += 1
            continue

        # UT1 files are one domain per line, but real-world scraped/curated
        # lists like this do accumulate stray whitespace-separated tokens
        # on rare lines (e.g. a domain plus a trailing comment). Keep only
        # the first token so a line like "example.com # note" cleans up
        # rather than getting rejected outright.
        token = token.split()[0] if token.split() else token

        if is_ip_address(token):
            ip_entries.append(token)
            continue

        if not DOMAIN_RE.match(token):
            malformed.append(token)
            continue

        if token in seen_in_category:
            duplicates_in_category += 1
            continue

        seen_in_category.add(token)
        cleaned.append(token)

    report["blank_or_comment"][name] = blank_or_comment
    report["ip_entries"][name] = ip_entries
    report["malformed"][name] = malformed
    report["duplicates_in_category"][name] = duplicates_in_category
    report["clean_count_pre_cross_dedup"][name] = len(cleaned)

    return cleaned


def main():
    OUTPUT_DIR.mkdir(exist_ok=True)

    report = {
        "raw_line_count": {},
        "blank_or_comment": {},
        "ip_entries": {},
        "malformed": {},
        "duplicates_in_category": {},
        "clean_count_pre_cross_dedup": {},
    }

    per_category_domains = {}
    for name, path in SOURCES.items():
        per_category_domains[name] = clean_category(name, path, report)

    # Cross-category dedup: the same domain can legitimately appear in more
    # than one raw UT1 category file (e.g. a site that is both gambling and
    # something else). For a single-label dataset we keep the first
    # category a domain is encountered in (dict insertion order below,
    # gambling -> drugs -> dangerous_material) and log every conflict
    # instead of silently dropping it.
    domain_to_category = {}
    cross_category_conflicts = []

    for name in SOURCES:
        for domain in per_category_domains[name]:
            if domain in domain_to_category:
                cross_category_conflicts.append(
                    (domain, domain_to_category[domain], name)
                )
                continue
            domain_to_category[domain] = name

    final_rows = sorted(domain_to_category.items())

    with open(OUTPUT_DIR / "cleaned_site_categories.csv", "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["domain", "category"])
        writer.writerows(final_rows)

    final_counts = defaultdict(int)
    for _, category in final_rows:
        final_counts[category] += 1

    lines = []
    lines.append("WellScreen Site-Category Dataset - Cleaning Report")
    lines.append("Source: UT1 Blacklists (Universite Toulouse Capitole), CC BY-SA 4.0")
    lines.append("Mirror: github.com/olbat/ut1-blacklists, fetched from raw files in raw/")
    lines.append("")
    lines.append("Per-category cleaning steps and counts")
    lines.append("=" * 60)
    for name in SOURCES:
        lines.append(f"\n[{name}]")
        lines.append(f"  raw lines read:                {report['raw_line_count'][name]}")
        lines.append(f"  blank/comment lines removed:   {report['blank_or_comment'][name]}")
        lines.append(f"  IP-address entries removed:    {len(report['ip_entries'][name])}")
        if report["ip_entries"][name]:
            sample = ", ".join(report["ip_entries"][name][:3])
            lines.append(f"    example(s): {sample}")
        lines.append(f"  malformed entries removed:     {len(report['malformed'][name])}")
        if report["malformed"][name]:
            sample = ", ".join(report["malformed"][name][:3])
            lines.append(f"    example(s): {sample}")
        lines.append(f"  in-category duplicates removed:{report['duplicates_in_category'][name]}")
        lines.append(
            f"  clean, category-unique count:  {report['clean_count_pre_cross_dedup'][name]}"
        )

    lines.append("\nCross-category resolution")
    lines.append("=" * 60)
    lines.append(f"  domains appearing in >1 category file: {len(cross_category_conflicts)}")
    for domain, kept_category, dropped_category in cross_category_conflicts[:10]:
        lines.append(
            f"    {domain}: kept as '{kept_category}', also listed under '{dropped_category}'"
        )
    if len(cross_category_conflicts) > 10:
        lines.append(f"    ... and {len(cross_category_conflicts) - 10} more (see script logic)")

    lines.append("\nFinal dataset")
    lines.append("=" * 60)
    total_raw = sum(report["raw_line_count"].values())
    total_final = len(final_rows)
    for name in SOURCES:
        lines.append(f"  {name}: {final_counts.get(name, 0)} domains")
    lines.append(f"  TOTAL raw lines across sources:  {total_raw}")
    lines.append(f"  TOTAL cleaned, deduplicated rows: {total_final}")
    lines.append(
        f"  Rows removed by cleaning: {total_raw - total_final} "
        f"({(total_raw - total_final) / total_raw:.1%} of raw input)"
    )

    report_text = "\n".join(lines)
    (OUTPUT_DIR / "cleaning_report.txt").write_text(report_text + "\n")
    print(report_text)


if __name__ == "__main__":
    main()
