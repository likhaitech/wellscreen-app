"""
Cleans the raw UT1 Blacklists category files in raw/ into a single labeled
dataset (domain,category) usable for WellScreen's proposed harmful-site
category detection (manuscript Table 6: "harmful website/category attempt").

Source: UT1 Blacklists (Universite Toulouse Capitole), maintained by
Fabrice Prigent - http://dsi.ut-capitole.fr/blacklists/index_en.php
Mirror used: https://github.com/olbat/ut1-blacklists (synced daily from the
UT1 site, CC BY-SA 4.0 licensed).

This is REAL, third-party-collected data - domain names that have been
manually reviewed and categorized by the UT1 project over many years for
use in real school/university web filters. It is not synthetic and not
generated by this project.

Categories included, and why:
  - gambling: casino/betting sites (Table 6's closest match for "harmful
    website/category attempt" in a general sense). UT1's own "gambling"
    folder PLUS a small, separately-sourced set of individually-verified
    Philippine online-casino brand domains (see
    raw/gambling_domains_ph_researched.txt for full sourcing and why it
    was added on top of UT1's list)
  - drugs: drug-related sites - UT1's own "drogue" folder (603 domains)
    PLUS a second, independently-maintained real source, The Block List
    Project's "drugs" list (26,029 domains, MIT licensed - see
    raw/drugs_domains_blocklistproject.txt for full sourcing and why it
    was added on top of UT1's smaller list)
  - dangerous_material: sites describing how to make weapons/explosives;
    UT1's own file also includes some pro-eating-disorder domains, which
    are self-harm-adjacent even though UT1 has no dedicated self-harm
    category (see README.md for the honest gap here)
  - adult: NOT from UT1 (see below) - a small, separately-sourced set of
    Philippines-specific pornography domains, added for local relevance.
    See raw/adult_domains_philippines.txt for full sourcing.

Deliberately NOT included: UT1's own "adult" category (4.6 million domains
- not practical to vet, store, or ship as a mobile asset for a school
project, and not needed to demonstrate the cleaning methodology, which is
the point of this exercise). A production version of this feature would
add it the same way, from the same source.

The "adult" category actually included here is different and much
smaller: only 3 domains (pornhub.com, xvideos.com, redtube.com),
individually named in real Philippine news coverage of the NTC's 2017
R.A. 9775 blocking order - researched via live web search, not guessed or
fabricated. No comprehensive official Philippines domain list exists
publicly (confirmed across multiple independent sources); this is stated
honestly as 3 real, sourced examples, not a complete Philippines
pornography blocklist. See raw/adult_domains_philippines.txt for the full
citation trail.

Run: python3 clean_dataset.py
Writes: output/cleaned_site_categories.csv, output/cleaning_report.txt
"""

import csv
import ipaddress
import re
from collections import defaultdict
from pathlib import Path

RAW_DIR = Path(__file__).parent / "raw"
OUTPUT_DIR = Path(__file__).parent / "output"

# Each category maps to a LIST of raw source files (usually one, "drugs"
# now has two - see raw/drugs_domains_blocklistproject.txt for why a
# second, independently-maintained real source was added on top of UT1's).
# Every file in the list is real, sourced, non-synthetic data; combining
# them widens the real training set for a category without ever mixing in
# anything fabricated. clean_category() below dedupes within a category
# regardless of which source file a domain came from.
SOURCES = {
    "gambling": [
        RAW_DIR / "gambling_domains.txt",
        # Philippines-specific, individually-verified additions - see that
        # file's header for full per-domain sourcing. Not from UT1.
        RAW_DIR / "gambling_domains_ph_researched.txt",
    ],
    "drugs": [
        RAW_DIR / "drugs_domains.txt",
        RAW_DIR / "drugs_domains_blocklistproject.txt",
    ],
    "dangerous_material": [RAW_DIR / "dangerous_material_domains.txt"],
    # Not from UT1, unlike the sources above - see the module docstring
    # and raw/adult_domains_philippines.txt for sourcing.
    "adult": [RAW_DIR / "adult_domains_philippines.txt"],
}

# Deliberately NOT part of SOURCES/cleaned_site_categories.csv above. This
# is a real, third-party "safe/benign" list (see
# raw/safe_domains_dnsfilter_raw.txt for full sourcing) used ONLY to give
# category_classifier.py negative examples during ML training - it is NOT
# a Table 6 harmful category, must NEVER end up in the app's bundled
# exact-match lookup CSV, and must NEVER be a value SiteCategoryService
# returns as a flagged category (that would need explicit handling
# everywhere a non-null category currently means "alert the parent" -
# simplest and safest is to just keep it out of that file entirely and
# only combine it in-memory for training, in
# build_ml_training_set_with_safe_class() below).
SAFE_SOURCE = RAW_DIR / "safe_domains_dnsfilter_raw.txt"

# Domains individually verified (checked by name against real, named
# legitimate organizations - not guessed or pattern-matched) to be
# genuinely legitimate sites mislabeled as "drugs" by the raw source
# files - not illicit online pharmacies, not drug marketplaces. Removed
# HERE, in the cleaning step itself, so the fix is reproducible and
# auditable in cleaning_report.txt, not a one-off hand edit of the output
# CSV.
#
# Why this exists: category_classifier_v1's live-deployment stress test
# found truepill.com (a real US pharmacy company) false-positiving as
# "drugs" at 95.5% confidence - see
# ml/site_category/output/category_classifier_evaluation.txt and
# validation/safe_pharmacy_health_heldout.txt. truepill.com itself was
# never IN the training data (it was the held-out probe that caught the
# problem) - but the training data DID contain real legitimate sites
# under the "drugs" label, which is exactly the kind of contamination
# that would push the model's learned decision boundary toward
# flagging other legitimate pharmacy/health-shaped domains. Removing
# known contamination is a direct, verifiable fix for a version of that
# same root cause, not a guarantee the false-positive class disappears
# entirely (re-tested after retraining - see README.md's drugs cleanup
# section for the honest before/after result).
#
# NOT EXHAUSTIVE: the raw "drugs" source is 26,667 lines total (603 from
# UT1 + 26,064 from The Block List Project) - too many to individually
# vet by hand. This list was built by checking ~85 well-known legitimate
# pharmacy/health/pharma-manufacturer/addiction-recovery/government-health
# domain names against the raw files, plus checking EVERY .gov entry
# (zero found) and EVERY .edu entry (4 found, all confirmed genuinely
# legitimate university health/education resources) - not a full manual
# review of all 26,667 lines. A spot-check of several hundred .org/.info
# entries confirmed the overwhelming majority are genuine illicit-pharmacy-
# spam-pattern domains (e.g. "1st-online-pharmacy.org",
# "amoxicillinbuyonline.info"), consistent with this source's documented
# purpose, not further undiscovered legitimate sites - so this is
# reported as a targeted, verified cleanup, not a claim that the
# remaining ~26,660 domains are all confirmed illicit.
KNOWN_MISLABELED_LEGITIMATE_DOMAINS = {
    "drugs": {
        "drugs.com",  # legitimate drug reference/information site
        "pharmacychecker.com",  # legitimate pharmacy price-comparison service
        "rxlist.com",  # legitimate drug reference site (WebMD network)
        "cesar.umd.edu",  # U. Maryland Center for Substance Abuse Research
        "chemweb.calpoly.edu",  # Cal Poly chemistry department resource
        "goaskalice.columbia.edu",  # Columbia University health Q&A service
        "prohibition.history.ohio-state.edu",  # OSU history dept resource on Prohibition
    },
}

# A deliberately simple, permissive FQDN check: labels separated by dots,
# each label alphanumeric/hyphen, 2+ char TLD. This is a data-QUALITY
# filter (reject obvious garbage), not a strict RFC 1035 validator.
DOMAIN_RE = re.compile(
    r"^(?!-)[a-z0-9-]{1,63}(?<!-)(\.(?!-)[a-z0-9-]{1,63}(?<!-))*\.[a-z]{2,}$"
)


def is_ip_address(token):
    try:
        ipaddress.ip_address(token)
        return True
    except ValueError:
        return False


def clean_category(name, paths, report):
    """[paths] is a list of one or more raw source files for this category
    (see SOURCES above) - all are combined into one cleaned, deduplicated
    list for `name`, with per-source raw line counts kept in the report so
    the cleaning report stays auditable down to which file each domain
    came from, even when a category has more than one real source."""
    if not isinstance(paths, (list, tuple)):
        paths = [paths]

    per_source_counts = {}
    raw_lines = []
    for path in paths:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        per_source_counts[path.name] = len(lines)
        raw_lines.extend(lines)

    report["raw_line_count"][name] = len(raw_lines)
    report["raw_line_count_by_source"][name] = per_source_counts

    blank_or_comment = 0
    ip_entries = []
    malformed = []
    seen_in_category = set()
    duplicates_in_category = 0
    cleaned = []

    for raw_line in raw_lines:
        token = raw_line.strip().lower()

        if not token or token.startswith("#") or token.startswith("//"):
            blank_or_comment += 1
            continue

        # UT1 files are one domain per line, but real-world scraped/curated
        # lists like this do accumulate stray whitespace-separated tokens
        # on rare lines (e.g. a domain plus a trailing comment). Keep only
        # the first token so a line like "example.com # note" cleans up
        # rather than getting rejected outright.
        token = token.split()[0] if token.split() else token

        if is_ip_address(token):
            ip_entries.append(token)
            continue

        if not DOMAIN_RE.match(token):
            malformed.append(token)
            continue

        if token in seen_in_category:
            duplicates_in_category += 1
            continue

        seen_in_category.add(token)
        cleaned.append(token)

    # Remove known-legitimate domains that ended up mislabeled in the raw
    # source (see KNOWN_MISLABELED_LEGITIMATE_DOMAINS above for the full
    # verification method and why). Logged explicitly, not silently
    # dropped, so the cleaning report stays auditable.
    known_legitimate = KNOWN_MISLABELED_LEGITIMATE_DOMAINS.get(name, set())
    excluded_legitimate = sorted(known_legitimate & set(cleaned))
    if excluded_legitimate:
        cleaned = [d for d in cleaned if d not in known_legitimate]

    report["blank_or_comment"][name] = blank_or_comment
    report["ip_entries"][name] = ip_entries
    report["malformed"][name] = malformed
    report["duplicates_in_category"][name] = duplicates_in_category
    report["excluded_known_legitimate"][name] = excluded_legitimate
    report["clean_count_pre_cross_dedup"][name] = len(cleaned)

    return cleaned


def main():
    OUTPUT_DIR.mkdir(exist_ok=True)

    report = {
        "raw_line_count": {},
        "raw_line_count_by_source": {},
        "blank_or_comment": {},
        "ip_entries": {},
        "malformed": {},
        "duplicates_in_category": {},
        "excluded_known_legitimate": {},
        "clean_count_pre_cross_dedup": {},
    }

    per_category_domains = {}
    for name, paths in SOURCES.items():
        per_category_domains[name] = clean_category(name, paths, report)

    # Cross-category dedup: the same domain can legitimately appear in more
    # than one raw UT1 category file (e.g. a site that is both gambling and
    # something else). For a single-label dataset we keep the first
    # category a domain is encountered in (dict insertion order below,
    # gambling -> drugs -> dangerous_material) and log every conflict
    # instead of silently dropping it.
    domain_to_category = {}
    cross_category_conflicts = []

    for name in SOURCES:
        for domain in per_category_domains[name]:
            if domain in domain_to_category:
                cross_category_conflicts.append(
                    (domain, domain_to_category[domain], name)
                )
                continue
            domain_to_category[domain] = name

    final_rows = sorted(domain_to_category.items())

    with open(OUTPUT_DIR / "cleaned_site_categories.csv", "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["domain", "category"])
        writer.writerows(final_rows)

    final_counts = defaultdict(int)
    for _, category in final_rows:
        final_counts[category] += 1

    lines = []
    lines.append("WellScreen Site-Category Dataset - Cleaning Report")
    lines.append("Sources: UT1 Blacklists (Universite Toulouse Capitole, CC BY-SA 4.0,")
    lines.append("  mirror github.com/olbat/ut1-blacklists) for gambling/drugs/")
    lines.append("  dangerous_material; The Block List Project (github.com/")
    lines.append("  blocklistproject/Lists, MIT) as a second real source for drugs;")
    lines.append("  see README.md and each raw/*.txt file's header for full per-")
    lines.append("  category sourcing.")
    lines.append("")
    lines.append("Per-category cleaning steps and counts")
    lines.append("=" * 60)
    for name in SOURCES:
        lines.append(f"\n[{name}]")
        by_source = report["raw_line_count_by_source"][name]
        if len(by_source) > 1:
            lines.append(f"  raw lines read:                {report['raw_line_count'][name]} (combined from {len(by_source)} sources)")
            for source_name, count in by_source.items():
                lines.append(f"    - {source_name}: {count}")
        else:
            lines.append(f"  raw lines read:                {report['raw_line_count'][name]}")
        lines.append(f"  blank/comment lines removed:   {report['blank_or_comment'][name]}")
        lines.append(f"  IP-address entries removed:    {len(report['ip_entries'][name])}")
        if report["ip_entries"][name]:
            sample = ", ".join(report["ip_entries"][name][:3])
            lines.append(f"    example(s): {sample}")
        lines.append(f"  malformed entries removed:     {len(report['malformed'][name])}")
        if report["malformed"][name]:
            sample = ", ".join(report["malformed"][name][:3])
            lines.append(f"    example(s): {sample}")
        lines.append(f"  in-category duplicates removed:{report['duplicates_in_category'][name]}")
        excluded = report["excluded_known_legitimate"].get(name, [])
        if excluded:
            lines.append(f"  known-legitimate domains removed: {len(excluded)}")
            lines.append(f"    {', '.join(excluded)}")
            lines.append(
                "    (verified individually against real, named legitimate"
                " organizations - see KNOWN_MISLABELED_LEGITIMATE_DOMAINS"
                " in this script for the full verification method)"
            )
        lines.append(
            f"  clean, category-unique count:  {report['clean_count_pre_cross_dedup'][name]}"
        )

    lines.append("\nCross-category resolution")
    lines.append("=" * 60)
    lines.append(f"  domains appearing in >1 category file: {len(cross_category_conflicts)}")
    for domain, kept_category, dropped_category in cross_category_conflicts[:10]:
        lines.append(
            f"    {domain}: kept as '{kept_category}', also listed under '{dropped_category}'"
        )
    if len(cross_category_conflicts) > 10:
        lines.append(f"    ... and {len(cross_category_conflicts) - 10} more (see script logic)")

    lines.append("\nFinal dataset")
    lines.append("=" * 60)
    total_raw = sum(report["raw_line_count"].values())
    total_final = len(final_rows)
    for name in SOURCES:
        lines.append(f"  {name}: {final_counts.get(name, 0)} domains")
    lines.append(f"  TOTAL raw lines across sources:  {total_raw}")
    lines.append(f"  TOTAL cleaned, deduplicated rows: {total_final}")
    lines.append(
        f"  Rows removed by cleaning: {total_raw - total_final} "
        f"({(total_raw - total_final) / total_raw:.1%} of raw input)"
    )

    report_text = "\n".join(lines)
    (OUTPUT_DIR / "cleaning_report.txt").write_text(report_text + "\n")
    print(report_text)

    build_ml_training_set_with_safe_class(domain_to_category, report)


def build_ml_training_set_with_safe_class(domain_to_category, report):
    """
    Writes output/ml_training_dataset_with_safe.csv: the same cleaned
    harmful-category rows as cleaned_site_categories.csv, PLUS a real
    "safe" class cleaned from SAFE_SOURCE - for train_category_classifier.py
    ONLY. This file must never be treated as the project's harmful-site
    dataset (that's still cleaned_site_categories.csv, unchanged) and must
    never be bundled into the app - see the SAFE_SOURCE comment above for
    why.
    """
    safe_report = {
        "raw_line_count": {},
        "raw_line_count_by_source": {},
        "blank_or_comment": {},
        "ip_entries": {},
        "malformed": {},
        "duplicates_in_category": {},
        "excluded_known_legitimate": {},
        "clean_count_pre_cross_dedup": {},
    }
    safe_domains = clean_category("safe", SAFE_SOURCE, safe_report)

    # Same safety-first rule as the harmful-vs-harmful cross-dedup above:
    # if a "safe" domain collides with an already-labeled harmful domain,
    # the harmful label wins and the collision is dropped from "safe"
    # rather than silently overwriting it.
    safe_conflicts = 0
    combined = dict(domain_to_category)
    for domain in safe_domains:
        if domain in combined:
            safe_conflicts += 1
            continue
        combined[domain] = "safe"

    rows = sorted(combined.items())
    with open(OUTPUT_DIR / "ml_training_dataset_with_safe.csv", "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["domain", "category"])
        writer.writerows(rows)

    counts = defaultdict(int)
    for _, category in rows:
        counts[category] += 1

    print("\nBuilt output/ml_training_dataset_with_safe.csv (ML training use only)")
    print(f"  safe: raw lines read: {safe_report['raw_line_count']['safe']}, "
          f"cleaned: {safe_report['clean_count_pre_cross_dedup']['safe']}, "
          f"dropped for colliding with an existing harmful domain: {safe_conflicts}")
    for name, count in sorted(counts.items()):
        print(f"  {name}: {count}")
    print(f"  TOTAL: {len(rows)}")


if __name__ == "__main__":
    main()
